/**
 * `pin1`, `pin2`, … — any pin number.
 *
 * This used to be an enumeration of "pin0"…"pin100". Chips with more than 100
 * pins (and BGA breakouts that expose every ball) could not be referenced by
 * number at all, so the key space is a template literal now.
 */
export type PinNumberNames = `pin${number}`

/** @deprecated use {@link PinNumberNames} — pin numbers are not capped at 100 */
export type PinNumbers100 = PinNumberNames

